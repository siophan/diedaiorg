def q(v):
    if v is None:
        return 'NULL'
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"

def ins(table, row):
    cols = ','.join(row.keys())
    vals = ','.join(q(v) for v in row.values())
    L.append(f"INSERT INTO {table} ({cols}) VALUES ({vals});")

import re as _re
def to_html(text):
    out=[]
    for line in str(text or '').split('\n'):
        line=line.strip()
        if not line: continue
        m=_re.match(r'^\[\[IMG:(.+?)\]\]$', line)
        if m: out.append('<figure><img src="%s" alt=""></figure>' % m.group(1)); continue
        line=line.replace('&','&amp;').replace('<','&lt;').replace('>','&gt;')
        line=_re.sub(r'^【(.+?)】', r'<strong>【\1】</strong>', line)
        out.append('<p>%s</p>' % line)
    return ''.join(out)

